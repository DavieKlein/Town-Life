#!/usr/bin/env python3
"""
Town Life - the VaultTech staff gate (roll-down shutter with the red STAFF ONLY sign, approved s55 "variant B") as a sprite overlay.

The gate scene (scene.overlay_gate: only the gate, in the image frame of the Corner Market map) is rendered with the normal map
renderer (Blender, objects layer, same sharpening / grading), cropped and cut into a 2 x 2 block of 32x64 sprites (one 15-colour
palette). The field puts the sprites over the storeroom stairs once the flag vault_scene is set (tl_field_script.cpp).

Writes graphics/gate_b.bmp/.json (4 frames: top-left, top-right, bottom-left, bottom-right) and include/tl_gate_data.h.
Run:  python3 tools/gate_overlay.py [--rerender] [--fast] [--preview OUT.png]
"""
import os
import sys

import numpy as np
from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import build_assets as ba  # noqa: E402
import minigame_art as ma  # noqa: E402
import scene as scn  # noqa: E402


def main():
    force = "--rerender" in sys.argv
    fast = "--fast" in sys.argv
    s = scn.overlay_gate()
    img = ba.render(s, "objects", force, fast)
    a = np.array(img)
    mask = a[..., 3] >= 128
    ys, xs = np.where(mask)
    x0b, x1b, y0b, y1b = xs.min(), xs.max() + 1, ys.min(), ys.max() + 1
    print("gate bbox:", x0b, y0b, x1b, y1b, "size", x1b - x0b, y1b - y0b)
    assert x1b - x0b <= 64 and y1b - y0b <= 128, "gate does not fit 64 x 128"
    bx = int((x0b + x1b) // 2 - 32)
    by = int(y1b - 128)
    block = a[by:by + 128, bx:bx + 64].copy() if by >= 0 else None
    if block is None:
        pad = np.zeros((128, 64, 4), np.uint8)
        pad[-by:, :] = a[0:128 + by, bx:bx + 64]
        block = pad
    block[..., 3] = np.where(block[..., 3] >= 128, 255, 0)
    frames = []
    for row in range(2):
        for col in range(2):
            frames.append(Image.fromarray(block[row * 64:(row + 1) * 64, col * 32:(col + 1) * 32], "RGBA"))
    ma.write_sprite_sheet("gate_b", frames)
    with open(os.path.join(ROOT, "include", "tl_gate_data.h"), "w", newline="\n") as f:
        f.write("// Generated by tools/gate_overlay.py - do not edit by hand.\n#ifndef TL_GATE_DATA_H\n#define TL_GATE_DATA_H\n\n"
                f"// top-left of the 2 x 2 block of 32x64 gate sprites in image pixels of the corner_market map\n"
                f"#define GATE_IMAGE_X {bx}\n#define GATE_IMAGE_Y {by}\n\n#endif\n")
    if "--preview" in sys.argv:
        out = sys.argv[sys.argv.index("--preview") + 1]
        prev = Image.new("RGBA", (64, 128), (80, 80, 90, 255))
        prev.alpha_composite(Image.fromarray(block, "RGBA"))
        prev.resize((256, 512), Image.NEAREST).save(out)
    print("gate sprites written")


if __name__ == "__main__":
    main()
