#!/usr/bin/env python3
"""
Town Life - Victor Vault's golden car (compact 0.75x, 4.2 m, owner-approved s62) as sprites.
Source: tools/proposals/s62/car75/car_{se,nw}_q.png (+ palette.json), rendered by tools/blender_car.py + tools/car_sprites.py
(python3 tools/car_sprites.py DIR 64 0.75 --rerender). The car only drives along the avenue (x axis): SE = driving +x (front visible),
NW = driving -x (rear visible); the SW / NE facings are not needed yet.
Each facing is cut into 32x32 pieces (empty ones dropped; one 15-colour palette for both): graphics/car_se.bmp, car_nw.bmp
(32x32 frames) + include/tl_car_data.h (piece offsets relative to the car's ground centre).  Run: python3 tools/car_sprites_build.py
"""
import json
import os

import numpy as np
from PIL import Image

import minigame_art as ma

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
SRC = os.path.join(ROOT, "tools", "proposals", "s62", "car75")
FEET = (96, 74)


def main():
    pal = [tuple(c) for c in json.load(open(os.path.join(SRC, "palette.json")))]
    pal += [(0, 0, 0)] * (16 - len(pal))
    lookup = {c: i for i, c in enumerate(pal) if i}
    rows = ["// Generated by tools/car_sprites_build.py - do not edit by hand.", "#ifndef TL_CAR_DATA_H", "#define TL_CAR_DATA_H", "",
            "namespace tl", "{", "    struct car_piece", "    {", "        int frame;", "        int dx;     // top-left relative to the car's ground centre (pixels)",
            "        int dy;", "    };", ""]
    for name in ("se", "nw"):
        im = np.array(Image.open(os.path.join(SRC, f"car_{name}_q.png")).convert("RGBA"))
        ys, xs = np.nonzero(im[..., 3])
        x0, y0 = xs.min() // 32 * 32, ys.min() // 32 * 32
        frames, pieces = [], []
        for cy in range(y0, ys.max() + 1, 32):
            for cx in range(x0, xs.max() + 1, 32):
                blk = im[cy:cy + 32, cx:cx + 32]
                if blk.shape[0] < 32 or blk.shape[1] < 32:
                    pad = np.zeros((32, 32, 4), np.uint8)
                    pad[:blk.shape[0], :blk.shape[1]] = blk
                    blk = pad
                if not blk[..., 3].any():
                    continue
                idx = np.zeros((32, 32), np.uint8)
                for y in range(32):
                    for x in range(32):
                        if blk[y, x, 3]:
                            idx[y, x] = lookup.get(tuple(int(v) for v in blk[y, x, :3]), 15)
                frames.append(idx)
                pieces.append((len(frames) - 1, cx - FEET[0], cy - FEET[1]))
        pixels = [row for f in frames for row in f.tolist()]
        ma.write_bmp(os.path.join(ROOT, "graphics", f"car_{name}.bmp"), pixels, 32, 32 * len(frames), 4, pal[:16])
        with open(os.path.join(ROOT, "graphics", f"car_{name}.json"), "w", newline="\n") as f:
            f.write('{\n    "type": "sprite",\n    "height": 32\n}\n')
        rows.append(f"    constexpr car_piece car_{name}_pieces[] = {{")
        rows += [f"        {{ {a}, {b}, {c} }}," for a, b, c in pieces]
        rows += ["    };", f"    constexpr int car_{name}_count = {len(pieces)};", ""]
        print(name, len(pieces), "pieces", len(pieces) * 16, "tiles")
    rows += ["}", "", "#endif", ""]
    open(os.path.join(ROOT, "include", "tl_car_data.h"), "w", newline="\n").write("\n".join(rows))


if __name__ == "__main__":
    main()
